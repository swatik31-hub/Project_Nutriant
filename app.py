@app.route("/api/generate_plan", methods=["POST"])
def generate_plan():
    data = request.get_json(silent=True) or {}

    # Required field validation
    required = ["name", "age", "diet", "city", "country"]
    for field in required:
        if not str(data.get(field, "")).strip():
            return jsonify({"error": f"Field '{field}' is required."}), 400

    # Numeric validation
    try:
        age = int(data.get("age", 0))
        if not (1 <= age <= 120):
            raise ValueError
    except (ValueError, TypeError):
        return jsonify({"error": "Age must be a number between 1 and 120."}), 400

    # Guardrail: input safety check
    combined_input = " ".join(str(v) for v in data.values())
    if guardrail_check(combined_input):
        return jsonify({"error": "Input contains potentially unsafe content. Please revise your entries."}), 400

    # Agentic Tool 1: BMI calculation
    bmi_info = {"bmi": None, "category": "Unknown"}
    tdee = 2000  # default fallback
    try:
        weight = float(data.get("weight") or 0)
        height = float(data.get("height") or 0)
        if weight > 0 and height > 0:
            bmi_info = calculate_bmi(weight, height)
            # Agentic Tool 2: TDEE estimation
            tdee = estimate_calories(
                age=age,
                gender=data.get("gender", "male"),
                weight_kg=weight,
                height_cm=height,
                activity=data.get("activity", "moderate"),
            )
    except (ValueError, TypeError):
        pass  # silently fall back to defaults

    try:
        prompt   = build_nutrition_prompt(data, bmi_info, tdee)
        response = model.generate_text(prompt=prompt)
        plan     = response.strip()

        # Guardrail: output safety check
        if guardrail_check(plan):
            plan = (
                "I'm sorry, I was unable to generate a safe plan. "
                "Please consult a registered dietitian or healthcare professional."
            )

        plan += MEDICAL_DISCLAIMER
        return jsonify({
            "plan":     plan,
            "bmi":      bmi_info.get("bmi"),
            "bmi_cat":  bmi_info.get("category"),
            "tdee":     tdee,
        })
    except Exception as e:
        return jsonify({"error": f"Model error: {str(e)}"}), 500


@app.route("/api/query", methods=["POST"])
def query_agent():
    data         = request.get_json(silent=True) or {}
    user_query   = str(data.get("query", "")).strip()
    user_context = data.get("user_context", {})

    if not user_query:
        return jsonify({"error": "Query cannot be empty."}), 400

    # Guardrail: block harmful queries
    if guardrail_check(user_query):
        return jsonify({
            "answer": (
                "I'm sorry, I can't assist with that request as it may involve "
                "harmful advice. Please consult a qualified healthcare professional."
            )
        }), 200

    try:
        prompt   = build_query_prompt(user_query, user_context)
        response = model.generate_text(prompt=prompt)
        answer   = response.strip()

        # Guardrail: sanitise output
        if guardrail_check(answer):
            answer = (
                "I'm unable to provide that information safely. "
                "Please consult a registered dietitian or your doctor."
            )

        answer += "\n\n*— NutriBot · AI-generated · Not a substitute for professional medical advice.*"
        return jsonify({"answer": answer})
    except Exception as e:
        return jsonify({"error": f"Model error: {str(e)}"}), 500


@app.route("/api/recipe", methods=["POST"])
def recipe_agent():
    """Agentic tool — suggests healthy recipes from available ingredients."""
    data        = request.get_json(silent=True) or {}
    ingredients = str(data.get("ingredients", "")).strip()
    diet        = str(data.get("diet", "")).strip()
    condition   = str(data.get("condition", "")).strip()

    if not ingredients:
        return jsonify({"error": "Please provide at least some ingredients."}), 400

    if guardrail_check(ingredients + " " + condition):
        return jsonify({"error": "Input contains unsafe content. Please revise."}), 400

    try:
        prompt   = build_recipe_prompt(ingredients, diet, condition)
        response = model.generate_text(prompt=prompt)
        recipes  = response.strip()

        if guardrail_check(recipes):
            recipes = "Unable to generate safe recipes. Please consult a nutritionist."

        recipes += "\n\n*— NutriBot · AI-generated recipes · Always verify nutritional info with a professional.*"
        return jsonify({"recipes": recipes})
    except Exception as e:
        return jsonify({"error": f"Model error: {str(e)}"}), 500


