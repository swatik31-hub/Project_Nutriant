# ── Guardrails ─────────────────────────────────────────────────────────────────
HARMFUL_PATTERNS = [
    r"\bstarv(e|ing|ation)\b",
    r"fasting to death",
    r"\bpurg(e|ing)\b",
    r"laxative abuse",
    r"extreme (diet|restriction|fasting)",
    r"stop (your |all )?(medication|medicine|insulin|pills)",
    r"ignore (your |the )?(doctor|physician|specialist)",
    r"harmful supplement",
    r"eat nothing",
    r"crash diet",
]

def guardrail_check(text: str) -> bool:
    """Returns True if text contains harmful / unsafe content."""
    lower = text.lower()
    return any(re.search(p, lower) for p in HARMFUL_PATTERNS)

