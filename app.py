# ── Agentic Tool: BMI Calculator ───────────────────────────────────────────────
def calculate_bmi(weight_kg: float, height_cm: float) -> dict:
    """Agentic tool — calculates BMI and returns category."""
    if weight_kg <= 0 or height_cm <= 0:
        return {"bmi": None, "category": "Unknown"}
    h_m = height_cm / 100.0
    bmi = round(weight_kg / (h_m ** 2), 1)
    if bmi < 18.5:
        cat = "Underweight"
    elif bmi < 25.0:
        cat = "Normal weight"
    elif bmi < 30.0:
        cat = "Overweight"
    else:
        cat = "Obese"
    return {"bmi": bmi, "category": cat}

# ── Agentic Tool: Calorie Estimator (Mifflin-St Jeor) ─────────────────────────
ACTIVITY_MULTIPLIERS = {
    "sedentary":   1.2,
    "light":       1.375,
    "moderate":    1.55,
    "active":      1.725,
    "very active": 1.9,
}

def estimate_calories(age: int, gender: str, weight_kg: float,
                       height_cm: float, activity: str) -> int:
    """Agentic tool — estimates TDEE using Mifflin-St Jeor."""
    gender = gender.lower()
    if gender == "female":
        bmr = 10 * weight_kg + 6.25 * height_cm - 5 * age - 161
    else:
        bmr = 10 * weight_kg + 6.25 * height_cm - 5 * age + 5
    multiplier = ACTIVITY_MULTIPLIERS.get(activity.lower(), 1.55)
    return round(bmr * multiplier)

